"""Trace report: requirement -> scenario -> model element -> generated test -> result.

Joins generated/*/trace.json with GoogleTest XML results. Exit code 1 when a requirement verified
by SIL has no test, or when a traced test failed or did not run.

    python3 -m tools.trace --results build/linux-host/test-results [--out reports]
"""
from __future__ import annotations

import argparse
import json
import pathlib
import sys
import xml.etree.ElementTree as ET  # noqa: S405 (local, trusted test output)

import yaml

REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]


def load_results(results_dir: pathlib.Path) -> dict[str, str]:
    """Returns {"Suite.Test": "passed" | "failed" | "skipped"}."""
    status: dict[str, str] = {}
    for xml_file in sorted(results_dir.rglob("*.xml")):
        try:
            root = ET.parse(xml_file).getroot()  # noqa: S314
        except ET.ParseError:
            continue
        for case in root.iter("testcase"):
            key = f"{case.get('classname')}.{case.get('name')}"
            if case.find("failure") is not None or case.find("error") is not None:
                result = "failed"
            elif case.find("skipped") is not None or case.get("result") == "skipped":
                result = "skipped"
            else:
                result = "passed"
            # A failure anywhere wins over a pass recorded elsewhere.
            if status.get(key) != "failed":
                status[key] = result
    return status


def build_report(results: dict[str, str]) -> tuple[list[dict], list[str]]:
    projects = yaml.safe_load((REPO_ROOT / "ea_projects.yaml").read_text(encoding="utf-8"))["projects"]
    rows, problems = [], []
    for p in projects:
        trace = json.loads((REPO_ROOT / p["output"] / "trace.json").read_text(encoding="utf-8"))
        suite = trace["sil_suite"]
        tests = {t["name"]: t for t in trace["tests"]}
        for t in trace["tests"]:
            if results.get(f"{suite}.{t['name']}") is None:
                problems.append(f"{p['name']}: test {suite}.{t['name']} has no result (not run?)")
        for r in trace["requirements"]:
            outcomes = {name: results.get(f"{suite}.{name}", "missing") for name in r["tests"]}
            if "sil" in r["verification"]:
                if not outcomes:
                    verdict = "NOT COVERED"
                elif all(v == "passed" for v in outcomes.values()):
                    verdict = "PASSED"
                else:
                    verdict = "FAILED"
            else:
                verdict = "PASSED" if outcomes and all(v == "passed" for v in outcomes.values()) else "NO SIL"
            if verdict in ("FAILED", "NOT COVERED"):
                problems.append(f"{p['name']}: {r['id']} {verdict}")
            rows.append({
                "project": p["name"],
                "id": r["id"],
                "asil": r["asil"],
                "verification": r["verification"],
                "text": r["text"],
                "satisfied_by": r["satisfied_by"],
                "tests": [{"name": n, "scenario": tests[n]["scenario"], "source": f"{tests[n]['feature']}:{tests[n]['line']}",
                           "result": outcomes[n]} for n in r["tests"]],
                "verdict": verdict,
            })
    return rows, problems


def to_markdown(rows: list[dict]) -> str:
    out = ["# Requirements trace matrix", "",
           "Generated by `python3 -m tools.trace` from `generated/*/trace.json` and GoogleTest results.", ""]
    project = None
    for r in rows:
        if r["project"] != project:
            project = r["project"]
            out += ["", f"## {project}", "", "| Requirement | ASIL | Verdict | Model elements | Tests |", "|---|---|---|---|---|"]
        tests = "<br>".join(f"{t['name']} ({t['result']})" for t in r["tests"]) or "-"
        model = "<br>".join(r["satisfied_by"]) or "-"
        out.append(f"| **{r['id']}** {r['text']} | {r['asil']} | {r['verdict']} | {model} | {tests} |")
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python3 -m tools.trace")
    ap.add_argument("--results", type=pathlib.Path, required=True, help="directory with GoogleTest XML files")
    ap.add_argument("--out", type=pathlib.Path, default=REPO_ROOT / "reports")
    args = ap.parse_args(argv)
    if not args.results.is_dir():
        print(f"results directory {args.results} does not exist", file=sys.stderr)
        return 1
    rows, problems = build_report(load_results(args.results))
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "trace_matrix.md").write_text(to_markdown(rows), encoding="utf-8")
    (args.out / "trace_matrix.json").write_text(json.dumps(rows, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    passed = sum(1 for r in rows if r["verdict"] == "PASSED")
    print(f"{passed}/{len(rows)} requirements PASSED; report: {args.out / 'trace_matrix.md'}")
    for p in problems:
        print(f"  {p}", file=sys.stderr)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
