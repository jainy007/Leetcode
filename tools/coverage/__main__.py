"""Structural coverage of generated product code: statement, branch and MC/DC (clang >= 18).

    LLVM_PROFILE_FILE=build/cov/%p-%m.profraw ctest --preset linux-host-coverage
    python3 -m tools.coverage [--build-dir build/linux-host-coverage] [--profiles build/cov]
                              [--report reports/coverage.md] [--update-baseline]

Scope: generated/<project>/src/*.cpp of every project in ea_projects.yaml. Objects: every
generated SIL and codec test executable. The report lists each uncovered MC/DC condition with its
source line, so that it can be closed by a test or justified.

Gate:
  - files of ASIL D-derived components (asil "D" or "X(D)") need 100 % MC/DC, except for the
    conditions justified in coverage_justifications.yaml (a stale justification also fails);
  - no file may fall below its branch / MC/DC entry in coverage_baseline.json (a ratchet: coverage
    may only rise; --update-baseline rewrites it).
"""
from __future__ import annotations

import argparse
import json
import os
import pathlib
import shutil
import subprocess
import sys

import yaml

from tools.gen.render import REPO_ROOT

BASELINE = REPO_ROOT / "coverage_baseline.json"
JUSTIFICATIONS = REPO_ROOT / "coverage_justifications.yaml"


def _d_derived(asil: str) -> bool:
    return asil == "D" or asil.endswith("(D)")


def _tool(name: str) -> str:
    for cand in (os.environ.get(name.upper().replace("-", "_")), f"{name}-18", name):
        if cand and shutil.which(cand):
            return cand
    sys.exit(f"{name} not found (set {name.upper().replace('-', '_')})")


def _pct(covered: int, count: int) -> float:
    return 100.0 if count == 0 else 100.0 * covered / count


def measure(build_dir: pathlib.Path, profiles: pathlib.Path) -> dict:
    raws = sorted(profiles.glob("*.profraw"))
    if not raws:
        sys.exit(f"no .profraw files in {profiles}")
    merged = profiles / "merged.profdata"
    subprocess.run([_tool("llvm-profdata"), "merge", "-sparse", *map(str, raws), "-o", str(merged)], check=True)
    exes = sorted(p for p in (build_dir / "generated").rglob("*")
                  if p.is_file() and os.access(p, os.X_OK) and p.name.endswith(("_sil", "_codec_test")))
    cmd = [_tool("llvm-cov"), "export", str(exes[0])] + [a for e in exes[1:] for a in ("-object", str(e))]
    cmd += ["-instr-profile", str(merged), "-ignore-filename-regex", r"(_deps|/tests/|/sil/|/runtime/|\.hpp$)"]
    out = subprocess.run(cmd, check=True, capture_output=True, text=True).stdout
    return json.loads(out)


def summarize(export: dict) -> dict[str, dict]:
    projects = yaml.safe_load((REPO_ROOT / "ea_projects.yaml").read_text(encoding="utf-8"))["projects"]
    asil_of = {}
    for p in projects:
        model = yaml.safe_load((REPO_ROOT / p["model"]).read_text(encoding="utf-8"))
        asil_of[p["output"]] = model["component"]["asil"]
    files = {}
    for f in export["data"][0]["files"]:
        rel = pathlib.Path(f["filename"]).resolve().relative_to(REPO_ROOT).as_posix()
        out_dir = "/".join(rel.split("/")[:2])
        if not rel.startswith("generated/") or "/src/" not in rel or out_dir not in asil_of:
            continue
        s = f["summary"]
        lines = (REPO_ROOT / rel).read_text(encoding="utf-8").splitlines()
        uncovered = []
        for rec in f.get("mcdc_records", []):
            line, col, conds = rec[0], rec[1], rec[-1]
            for i, ok in enumerate(conds):
                if not ok:
                    uncovered.append({"line": line, "col": col, "condition": i + 1, "of": len(conds),
                                      "source": lines[line - 1].strip()})
        files[rel] = {
            "asil": asil_of[out_dir],
            "lines": _pct(s["lines"]["covered"], s["lines"]["count"]),
            "branches": _pct(s["branches"]["covered"], s["branches"]["count"]),
            "mcdc": _pct(s["mcdc"]["covered"], s["mcdc"]["count"]),
            "uncovered_mcdc": uncovered,
        }
    return files


def report(files: dict[str, dict]) -> str:
    out = ["# Structural coverage of generated code", "",
           "Generated by `python3 -m tools.coverage` from the SIL and codec tests (clang MC/DC).", "",
           "| File | ASIL | Lines | Branches | MC/DC |", "|---|---|---|---|---|"]
    for rel, f in sorted(files.items()):
        out.append(f"| `{rel}` | {f['asil']} | {f['lines']:.1f} % | {f['branches']:.1f} % | {f['mcdc']:.1f} % |")
    out += ["", "## Uncovered MC/DC conditions", ""]
    for rel, f in sorted(files.items()):
        for u in f["uncovered_mcdc"]:
            note = f" Justified: {' '.join(u['justified'].split())}" if u.get("justified") else ""
            out.append(f"- `{rel}:{u['line']}` condition {u['condition']} of {u['of']}: `{u['source']}`.{note}")
    return "\n".join(out) + "\n"


def gate(files: dict[str, dict], baseline: dict[str, dict], justified: list[dict]) -> list[str]:
    errors = []
    used = set()
    for rel, f in sorted(files.items()):
        if _d_derived(f["asil"]):
            for u in f["uncovered_mcdc"]:
                hit = next((i for i, j in enumerate(justified) if j["file"] == rel and j["source"] in u["source"]
                            and j["condition"] == u["condition"]), None)
                if hit is None:
                    errors.append(f"{rel}:{u['line']}: MC/DC condition {u['condition']} of {u['of']} not covered "
                                  f"and not justified: {u['source']}")
                else:
                    used.add(hit)
                    u["justified"] = justified[hit]["reason"]
        base = baseline.get(rel)
        if base is None:
            continue
        for key in ("branches", "mcdc"):
            if round(f[key], 2) < base[key]:
                errors.append(f"{rel}: {key} coverage {f[key]:.2f} % fell below the baseline {base[key]:.2f} %")
    for i, j in enumerate(justified):
        if i not in used:
            errors.append(f"stale justification in {JUSTIFICATIONS.name}: {j['file']} '{j['source']}' condition {j['condition']}")
    return errors


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python3 -m tools.coverage")
    ap.add_argument("--build-dir", type=pathlib.Path, default=REPO_ROOT / "build" / "linux-host-coverage")
    ap.add_argument("--profiles", type=pathlib.Path, default=REPO_ROOT / "build" / "cov")
    ap.add_argument("--report", type=pathlib.Path, default=REPO_ROOT / "reports" / "coverage.md")
    ap.add_argument("--update-baseline", action="store_true")
    args = ap.parse_args(argv)
    files = summarize(measure(args.build_dir, args.profiles))
    justified = yaml.safe_load(JUSTIFICATIONS.read_text(encoding="utf-8"))["justifications"] if JUSTIFICATIONS.is_file() else []
    if args.update_baseline:
        BASELINE.write_text(json.dumps({k: {"branches": round(v["branches"], 2), "mcdc": round(v["mcdc"], 2)}
                                        for k, v in sorted(files.items())}, indent=2) + "\n", encoding="utf-8")
        print(f"baseline written: {BASELINE.relative_to(REPO_ROOT)}")
    baseline = json.loads(BASELINE.read_text(encoding="utf-8")) if BASELINE.is_file() else {}
    errors = gate(files, baseline, justified)
    args.report.parent.mkdir(parents=True, exist_ok=True)
    args.report.write_text(report(files), encoding="utf-8")
    for e in errors:
        print(e)
    n = sum(len(f["uncovered_mcdc"]) for f in files.values())
    print(f"{len(files)} generated file(s); {n} uncovered MC/DC condition(s); report: {args.report}")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
